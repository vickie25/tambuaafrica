const fs = require("fs");
const path = require("path");
const sharp = require("sharp");

const rootDir = path.resolve(__dirname, "..");
const publicDir = path.join(rootDir, "public");
const imagesDir = path.join(publicDir, "images");
const outputDir = path.join(imagesDir, "_responsive");
const generatedDir = path.join(rootDir, "src", "generated");
const manifestPath = path.join(generatedDir, "responsive-images.ts");

const WIDTHS = [480, 768, 1024, 1366, 1600];
const MIN_BYTES = 24 * 1024;
const IMAGE_RE = /\.(jpe?g|png|webp)$/i;

function toPublicPath(filePath) {
  return `/${path.relative(publicDir, filePath).replace(/\\/g, "/")}`;
}

function toOutputPath(sourcePath, width) {
  const rel = path.relative(imagesDir, sourcePath);
  const parsed = path.parse(rel);
  return path.join(outputDir, parsed.dir, `${parsed.name}-${width}w.webp`);
}

function walk(dir, files = []) {
  if (!fs.existsSync(dir)) return files;

  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const fullPath = path.join(dir, entry.name);
    if (entry.isDirectory()) {
      if (fullPath === outputDir) continue;
      walk(fullPath, files);
    } else if (IMAGE_RE.test(entry.name)) {
      files.push(fullPath);
    }
  }

  return files;
}

async function generateVariant(sourcePath, width) {
  const outPath = toOutputPath(sourcePath, width);
  fs.mkdirSync(path.dirname(outPath), { recursive: true });

  const sourceStat = fs.statSync(sourcePath);
  if (fs.existsSync(outPath) && fs.statSync(outPath).mtimeMs >= sourceStat.mtimeMs) {
    return;
  }

  await sharp(sourcePath)
    .rotate()
    .resize({ width, withoutEnlargement: true, fit: "inside" })
    .webp({ quality: width >= 1366 ? 76 : 72, effort: 5, smartSubsampling: true })
    .toFile(outPath);
}

async function main() {
  const manifest = {};
  let generated = 0;

  for (const sourcePath of walk(imagesDir)) {
    const stat = fs.statSync(sourcePath);
    if (stat.size < MIN_BYTES) continue;

    let metadata;
    try {
      metadata = await sharp(sourcePath).metadata();
    } catch (error) {
      console.warn(`Skipping unreadable image: ${sourcePath} (${error.message})`);
      continue;
    }

    if (!metadata.width) continue;

    const widths = WIDTHS.filter((width) => width < metadata.width);
    if (widths.length === 0) continue;

    for (const width of widths) {
      await generateVariant(sourcePath, width);
      generated += 1;
    }

    const sourcePublicPath = toPublicPath(sourcePath);
    manifest[sourcePublicPath] = widths.map((width) => ({
      width,
      src: toPublicPath(toOutputPath(sourcePath, width)),
    }));
  }

  fs.mkdirSync(generatedDir, { recursive: true });
  const body =
    `/* This file is generated by scripts/generate-responsive-images.cjs. */\n` +
    `export type ResponsiveImageVariant = { src: string; width: number };\n\n` +
    `export const responsiveImages: Record<string, ResponsiveImageVariant[]> = ${JSON.stringify(manifest, null, 2)};\n`;

  fs.writeFileSync(manifestPath, body);
  console.log(`Responsive image manifest written with ${Object.keys(manifest).length} images and ${generated} variants.`);
}

main().catch((error) => {
  console.error(error);
  process.exit(1);
});
